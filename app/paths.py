"""
路径适配层 —— 同时兼容源码运行 / PyInstaller frozen 模式
================================================================

源码模式:
  可执行根      = 项目根 (包含 app/ 目录)
  static 目录   = app/static/ (只读，从源码读取)
  plugins 目录  = app/tools/plugins/ (可写)

Frozen 模式 (PyInstaller onedir):
  sys._MEIPASS  = exe 旁边的 _internal/ 目录
  static 目录   = sys._MEIPASS/app/static/ (只读，打包时一起进 exe)
  plugins 目录  = %APPDATA%/DeepHub-MAX/plugins/ (可写，启动时从内置模板拷贝)
"""

import os
import sys
import shutil
from pathlib import Path


# ─── Frozen? ────────────────────────────────────────────────────
FROZEN = getattr(sys, "frozen", False)

if FROZEN:
    # PyInstaller onedir: exe 旁边有 _internal/
    # _MEIPASS 指向 _internal/
    _MEI = Path(getattr(sys, "_MEIPASS", Path(sys.executable).parent))
    APP_ROOT = _MEI
else:
    APP_ROOT = Path(__file__).resolve().parent.parent  # ai-harness/


# ─── Static 前端资源 (只读) ──────────────────────────────────────
STATIC_DIR = APP_ROOT / "app" / "static"
RESOURCES_DIR = APP_ROOT / "app" / "resources"


# ─── Plugins 目录 (可写，AI 动态创建插件要落盘) ──────────────────
if FROZEN:
    # 写到 %APPDATA% 下，用户升级 exe 不丢数据
    _APPDATA = Path(os.environ.get("APPDATA", Path.home()))
    USER_DATA_DIR = _APPDATA / "DeepHub-MAX"
    PLUGINS_DIR = USER_DATA_DIR / "plugins"
else:
    PLUGINS_DIR = APP_ROOT / "app" / "tools" / "plugins"
    USER_DATA_DIR = PLUGINS_DIR.parent.parent  # 仅作为占位


# ─── 初始化 ─────────────────────────────────────────────────────
def ensure_dirs():
    """确保 plugins 目录存在。frozen 模式下从 exe 内部拷贝模板 __init__.py"""
    PLUGINS_DIR.mkdir(parents=True, exist_ok=True)
    init_py = PLUGINS_DIR / "__init__.py"
    if not init_py.exists():
        init_py.write_text("# Auto-generated by DeepHub-MAX\n", encoding="utf-8")
    # frozen 模式：把打包进去的 tools/plugins 里的额外插件拷出来
    if FROZEN:
        _builtin_plugins = APP_ROOT / "app" / "tools" / "plugins"
        if _builtin_plugins.is_dir():
            for f in _builtin_plugins.glob("*.py"):
                if f.name == "__init__.py":
                    continue
                dest = PLUGINS_DIR / f.name
                if not dest.exists():
                    shutil.copy2(f, dest)
